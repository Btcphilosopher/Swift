                    Circle()
                        .fill(.green)
                        .frame(
                            width: 8,
                            height: 8
                        )
                }
            }

            if let route =
                speaker.activeRoute {

                Text(route.name)
                    .font(.subheadline)
                    .foregroundStyle(.secondary)
            }

            Divider()

            HStack {

                Image(
                    systemName:
                        "speaker.wave.1"
                )

                Text(
                    "\(Int(speaker.systemVolume * 100))%"
                )
                .monospacedDigit()

                Spacer()

                Button {

                    speaker.toggleMute()

                } label: {

                    Image(
                        systemName:
                            speaker.isMuted
                            ? "speaker.wave.2"
                            : "speaker.slash"
                    )
                }
                .buttonStyle(.bordered)
            }

            Divider()

            Picker(
                "Mode",
                selection:
                    Binding(
                        get: {
