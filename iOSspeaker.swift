// MARK: - Speaker Route

struct SpeakerRoute: Identifiable, Equatable {
    let id = UUID()
    let name: String
    let type: SpeakerOutputType
    let channels: Int
    let sampleRate: Double
    let isActive: Bool
}

// MARK: - Audio Metrics

struct SpeakerMetrics {
    var peakLevel: Float = 0
    var rmsLevel: Float = 0
    var clipping: Bool = false
    var sampleRate: Double = 44_100
    var outputChannels: Int = 2
}

// MARK: - Speaker Configuration

struct SpeakerConfiguration {
    var mode: SpeakerMode = .standard

    var bass: Double = 0
    var treble: Double = 0
    var balance: Double = 0

    var equalizerEnabled = false
    var spatialAudioEnabled = false

    var volumeLimit: Double = 1.0

    var soundCheckEnabled = false
}

// MARK: - Speaker System

@MainActor
final class SpeakerSystem: NSObject,
                           ObservableObject,
                           AVAudioPlayerDelegate {

    // MARK: Published State

    @Published private(set) var routes: [SpeakerRoute] = []

    @Published private(set) var activeRoute: SpeakerRoute?

    @Published private(set) var systemVolume: Float = 0

    @Published private(set) var metrics = SpeakerMetrics()

    @Published var configuration = SpeakerConfiguration()

    @Published var isMuted = false

    @Published var isPlayingTestTone = false

    @Published var audioSessionActive = false

    // MARK: Private

    private let audioSession = AVAudioSession.sharedInstance()

    private var volumeObservation: NSKeyValueObservation?

    private var testPlayer: AVAudioPlayer?

    private var timer: Timer?

    // MARK: Init

    override init() {
        super.init()

        configureNotifications()
        observeSystemVolume()
        refreshRoute()
    }

    deinit {
        NotificationCenter.default.removeObserver(self)
        volumeObservation?.invalidate()
        timer?.invalidate()
    }

    // MARK: Audio Session

    func activate() throws {

        try audioSession.setCategory(
            .playback,
            mode: .default,
            options: [
                .allowAirPlay,
                .allowBluetoothA2DP
            ]
        )

        try audioSession.setActive(
            true,
            options: []
        )

        audioSessionActive = true

        refreshRoute()
    }

    func deactivate() {

        do {
            try audioSession.setActive(
                false,
                options: [.notifyOthersOnDeactivation]
            )
        } catch {
            print("Audio session deactivation failed: \(error)")
        }

        audioSessionActive = false
    }

    // MARK: Route Detection

    func refreshRoute() {

        let currentRoute = audioSession.currentRoute

        routes = currentRoute.outputs.map {
            SpeakerRoute(
                name: $0.portName,
                type: outputType(for: $0.portType),
                channels: $0.channels?.count ?? 2,
                sampleRate: audioSession.sampleRate,
                isActive: true
            )
        }

        activeRoute = routes.first

        metrics.sampleRate = audioSession.sampleRate
        metrics.outputChannels =
            currentRoute.outputs.first?.channels?.count ?? 2
    }

    private func outputType(
        for portType: AVAudioSession.Port
    ) -> SpeakerOutputType {

        switch portType {

        case .builtInSpeaker:
            return .builtInSpeaker

        case .headphones,
             .headsetMic:
            return .headphones

        case .bluetoothA2DP,
             .bluetoothHFP,
             .bluetoothLE:
            return .bluetooth

        case .airPlay:
            return .airPlay

        case .usbAudio:
            return .usb

        case .carAudio:
            return .carAudio

        case .HDMI,
             .displayPort:
            return .receiver

        default:
            return .unknown
        }
    }

    // MARK: Volume

    private func observeSystemVolume() {

        systemVolume = audioSession.outputVolume

        volumeObservation =
            audioSession.observe(
                \.outputVolume,
                options: [.initial, .new]
            ) { [weak self] session, _ in

                Task { @MainActor in
                    self?.systemVolume =
                        session.outputVolume
                }
            }
    }

    // MARK: Application Volume

    var effectiveVolume: Double {

        if isMuted {
            return 0
        }

        return min(
            Double(systemVolume),
            configuration.volumeLimit
        )
    }

    func setVolumeLimit(_ value: Double) {

        configuration.volumeLimit =
            min(max(value, 0), 1)
    }

    // MARK: Mute

    func toggleMute() {
        isMuted.toggle()
    }

    func mute() {
        isMuted = true
    }

    func unmute() {
        isMuted = false
    }

    // MARK: Equalizer

    func setBass(_ value: Double) {

        configuration.bass =
            min(max(value, -12), 12)
    }

    func setTreble(_ value: Double) {

        configuration.treble =
            min(max(value, -12), 12)
    }

    func setBalance(_ value: Double) {

        configuration.balance =
            min(max(value, -1), 1)
    }

    // MARK: Modes

    func setMode(_ mode: SpeakerMode) {

        configuration.mode = mode

        switch mode {

        case .standard:
            configuration.bass = 0
            configuration.treble = 0
            configuration.spatialAudioEnabled = false

        case .music:
            configuration.bass = 3
            configuration.treble = 2
            configuration.spatialAudioEnabled = false

        case .movie:
            configuration.bass = 5
            configuration.treble = 3
            configuration.spatialAudioEnabled = true

        case .voice:
            configuration.bass = -2
            configuration.treble = 4
            configuration.spatialAudioEnabled = false

        case .gaming:
            configuration.bass = 3
            configuration.treble = 4
            configuration.spatialAudioEnabled = true

        case .spatial:
            configuration.bass = 2
            configuration.treble = 2
            configuration.spatialAudioEnabled = true
        }
    }

    // MARK: Spatial Audio Preference

    func setSpatialAudio(_ enabled: Bool) {

        configuration.spatialAudioEnabled = enabled
    }

    // MARK: Notifications

    private func configureNotifications() {

        NotificationCenter.default.addObserver(
            self,
            selector: #selector(handleRouteChange),
            name: AVAudioSession.routeChangeNotification,
            object: audioSession
        )

        NotificationCenter.default.addObserver(
            self,
            selector: #selector(handleInterruption),
            name: AVAudioSession.interruptionNotification,
            object: audioSession
        )

        NotificationCenter.default.addObserver(
            self,
            selector: #selector(handleMediaServicesReset),
            name: AVAudioSession.mediaServicesWereResetNotification,
            object: audioSession
        )
    }

    @objc
    private func handleRouteChange(
        _ notification: Notification
    ) {

        Task { @MainActor in
            self.refreshRoute()
        }
    }

    @objc
    private func handleInterruption(
        _ notification: Notification
    ) {

        guard
            let info = notification.userInfo,
            let typeValue =
                info[AVAudioSessionInterruptionTypeKey]
                    as? UInt,
            let type =
                AVAudioSession.InterruptionType(
                    rawValue: typeValue
                )
        else {
            return
        }

        Task { @MainActor in

            switch type {

            case .began:
                self.isPlayingTestTone = false

            case .ended:
                self.refreshRoute()

                try? self.audioSession.setActive(
                    true
                )

            @unknown default:
                break
            }
        }
    }

    @objc
    private func handleMediaServicesReset(
        _ notification: Notification
    ) {

        Task { @MainActor in

            self.audioSessionActive = false

            try? self.activate()
        }
    }

    // MARK: Test Tone

    func playTestTone() {

        guard !isPlayingTestTone else {
            stopTestTone()
            return
        }

        let sampleRate = 44_100
        let duration = 1.0
        let frequency = 440.0

        let frameCount =
            Int(Double(sampleRate) * duration)

        var samples = [Float](
            repeating: 0,
            count: frameCount
        )

        for i in 0..<frameCount {

            let t =
                Double(i) /
                Double(sampleRate)

            let envelope =
                min(
                    1,
                    min(
                        t / 0.02,
                        (duration - t) / 0.05
                    )
                )

            samples[i] =
                Float(
                    sin(
                        2 * Double.pi *
                        frequency *
                        t
                    )
                ) *
                Float(envelope) *
                0.15
        }

        let url =
            FileManager.default
                .temporaryDirectory
                .appendingPathComponent(
                    "speaker_test.wav"
                )

        do {

            try writeWAV(
                samples: samples,
                sampleRate: sampleRate,
                url: url
            )

            testPlayer =
                try AVAudioPlayer(contentsOf: url)

            testPlayer?.delegate = self
            testPlayer?.volume =
                Float(effectiveVolume)

            isPlayingTestTone =
                testPlayer?.play() ?? false

            startMetricsMonitoring()

        } catch {

            print(
                "Test tone failed: \(error)"
            )
        }
    }

    func stopTestTone() {

        testPlayer?.stop()
        testPlayer = nil

        isPlayingTestTone = false

        stopMetricsMonitoring()
    }

    // MARK: WAV Generator

    private func writeWAV(
        samples: [Float],
        sampleRate: Int,
        url: URL
    ) throws {

        let channels: UInt16 = 1
        let bitsPerSample: UInt16 = 16

        let byteRate =
            UInt32(sampleRate) *
            UInt32(channels) *
            UInt32(bitsPerSample / 8)

        let blockAlign =
            channels *
            (bitsPerSample / 8)

        var pcmData = Data()

        for sample in samples {

            let clamped =
                max(
                    -1,
                    min(1, sample)
                )

            let value =
                Int16(
                    clamped *
                    Float(Int16.max)
                )

            var littleEndian =
                value.littleEndian

            withUnsafeBytes(
                of: &littleEndian
            ) {
                pcmData.append(contentsOf: $0)
            }
        }

        var data = Data()

        data.append(contentsOf: Array("RIFF".utf8))

        var chunkSize =
            UInt32(36 + pcmData.count)

        data.append(
            Data(
                bytes: &chunkSize,
                count: 4
            )
        )

        data.append(contentsOf: Array("WAVE".utf8))
        data.append(contentsOf: Array("fmt ".utf8))

        var subChunk1Size: UInt32 = 16
        data.append(
            Data(
                bytes: &subChunk1Size,
                count: 4
            )
        )

        var audioFormat: UInt16 = 1
        data.append(
            Data(
                bytes: &audioFormat,
                count: 2
            )
        )

        data.append(
            Data(
                bytes: &channels,
                count: 2
            )
        )

        var rate =
            UInt32(sampleRate)

        data.append(
            Data(
                bytes: &rate,
                count: 4
            )
        )

        data.append(
            Data(
                bytes: &byteRate,
                count: 4
            )
        )

        data.append(
            Data(
                bytes: &blockAlign,
                count: 2
            )
        )

        data.append(
            Data(
                bytes: &bitsPerSample,
                count: 2
            )
        )

        data.append(contentsOf: Array("data".utf8))

        var dataSize =
            UInt32(pcmData.count)

        data.append(
            Data(
                bytes: &dataSize,
                count: 4
            )
        )

        data.append(pcmData)

        try data.write(to: url)
    }

    // MARK: Metrics

    private func startMetricsMonitoring() {

        timer?.invalidate()

        timer =
            Timer.scheduledTimer(
                withTimeInterval: 0.05,
                repeats: true
            ) { [weak self] _ in

                guard let self else {
                    return
                }

                Task { @MainActor in

                    guard
                        let player =
                            self.testPlayer
                    else {
                        return
                    }

                    let level =
                        Float(
                            player.volume
                        )

                    self.metrics.rmsLevel =
                        level

                    self.metrics.peakLevel =
                        min(
                            1,
                            level * 1.25
                        )

                    self.metrics.clipping =
                        self.metrics.peakLevel >= 0.98
                }
            }
    }

    private func stopMetricsMonitoring() {

        timer?.invalidate()
        timer = nil
    }

    // MARK: AVAudioPlayer Delegate

    nonisolated
    func audioPlayerDidFinishPlaying(
        _ player: AVAudioPlayer,
        successfully flag: Bool
    ) {

        Task { @MainActor in

            self.isPlayingTestTone = false
            self.stopMetricsMonitoring()
        }
    }
}

