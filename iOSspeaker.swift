                ForEach(
                    SpeakerMode.allCases
                ) { mode in

                    Text(mode.title)
                        .tag(mode)
                }

            }
            .pickerStyle(.menu)

            Button {

                speaker.playTestTone()

            } label: {

                Label(
                    speaker.isPlayingTestTone
                    ? "Stop Test"
                    : "Test Speaker",
                    systemImage:
                        speaker.isPlayingTestTone
                        ? "stop.fill"
                        : "waveform"
                )
                .frame(
                    maxWidth: .infinity
                )
            }
            .buttonStyle(.borderedProminent)
        }
        .padding()
    }
